const INDEX: Record<Language, number> = { en: -1, de: 0, fr: 1, it: 2, es: 3, hu: 4 };

export function localizedCapital(capital: string, language: Language): string {
  const index = INDEX[language];
  if (index < 0) return capital;
  return RAW[capital]?.split("|")[index] ?? capital;
}
